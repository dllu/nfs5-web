const thread = view.getUint32(data + 512, true);
assert.equal(invoke('GetThreadPriority', thread), 0);
assert.equal(invoke('SetThreadPriority', 0xfffffffe, 2), 1);
assert.equal(invoke('GetThreadPriority', thread), 2);
assert.equal(invoke('WaitForSingleObject', thread, 0), 258);
