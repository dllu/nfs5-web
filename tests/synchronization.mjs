assert.equal(invoke('WaitForSingleObject', manual, 0), 0xffffffff, 'DUPLICATE_CLOSE_SOURCE closes only the old handle');
assert.equal(invoke('WaitForSingleObject', duplicate, 0), 0);
assert.equal(invoke('CloseHandle', duplicate), 1);
