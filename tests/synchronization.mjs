import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { webcrypto } from 'node:crypto';
import { loadRuntime } from '../dist/runtime.mjs';

globalThis.crypto ??= webcrypto;
const runtime = await loadRuntime({ read: async path => new Response(await readFile(new URL('../dist/' + path, import.meta.url))) });
const { module, base, manifest } = runtime;
const view = new DataView(module.HEAPU8.buffer, base);
const stack = runtime.memorySize - 0x10000, data = 0x800000;
let calls = 0;
function invoke(name, ...args) {
  const item = manifest.imports.find(item => item.dll === 'KERNEL32.dll' && item.name === name);
  assert(item, name);
  args.forEach((value, i) => view.setUint32(stack + i * 4, value >>> 0, true));
  module._web_set_register(4, stack);
  assert.equal(module._web_run(item.slot, 2000), 0, module.UTF8ToString(module._web_error()));
  const regs = new Uint32Array(module.HEAPU8.buffer, module._web_registers(), 8);
  assert.equal(regs[4], stack + args.length * 4, `${name} stdcall cleanup`);
  calls++;
  return regs[0];
}
module.HEAPU8.set(Buffer.from('NFS5 test mutex\0'), base + data);
const mutex = invoke('CreateMutexA', 0, 1, data);
assert(mutex);
assert.equal(invoke('GetLastError'), 0);
const alias = invoke('CreateMutexA', 0, 0, data);
assert(alias && alias !== mutex, 'Named opens get independent handles');
assert.equal(invoke('GetLastError'), 183);
assert.equal(invoke('CreateEventA', 0, 0, 0, data), 0);
assert.equal(invoke('GetLastError'), 6);
assert.equal(invoke('WaitForSingleObject', alias, 0), 0);
assert.equal(invoke('ReleaseMutex', mutex), 1);
assert.equal(invoke('ReleaseMutex', alias), 1);
assert.equal(invoke('ReleaseMutex', alias), 0);
assert.equal(invoke('GetLastError'), 288);
assert.equal(invoke('CloseHandle', mutex), 1);
assert.equal(invoke('WaitForSingleObject', mutex, 0), 0xffffffff);
assert.equal(invoke('WaitForSingleObject', alias, 0), 0);
assert.equal(invoke('ReleaseMutex', alias), 1);
assert.equal(invoke('CloseHandle', alias), 1);
assert.equal(invoke('OpenMutexA', 0x1f0001, 0, data), 0);
assert.equal(invoke('GetLastError'), 2);

const auto = invoke('CreateEventA', 0, 0, 1, 0);
const manual = invoke('CreateEventA', 0, 1, 0, 0);
view.setUint32(data + 256, auto, true); view.setUint32(data + 260, manual, true);
assert.equal(invoke('WaitForMultipleObjectsEx', 2, data + 256, 1, 0, 0), 258);
assert.equal(invoke('WaitForSingleObject', auto, 0), 0, 'A failed wait-all cannot consume an auto-reset event');
assert.equal(invoke('WaitForSingleObject', auto, 0), 258);
assert.equal(invoke('SetEvent', auto), 1);
assert.equal(invoke('SetEvent', manual), 1);
assert.equal(invoke('WaitForMultipleObjectsEx', 2, data + 256, 1, 0, 0), 0);
assert.equal(invoke('WaitForSingleObject', auto, 0), 258);
assert.equal(invoke('WaitForSingleObject', manual, 0), 0);
assert.equal(invoke('WaitForSingleObject', manual, 0), 0);
assert.equal(invoke('ResetEvent', manual), 1);
assert.equal(invoke('WaitForSingleObject', manual, 0), 258);
assert.equal(invoke('SetEvent', manual), 1);
assert.equal(invoke('WaitForMultipleObjectsEx', 2, data + 256, 0, 0, 0), 1);

const semaphore = invoke('CreateSemaphoreA', 0, 1, 2, 0);
assert.equal(invoke('ReleaseSemaphore', semaphore, 2, data + 512), 0);
assert.equal(invoke('GetLastError'), 298);
assert.equal(invoke('WaitForSingleObject', semaphore, 0), 0);
assert.equal(invoke('WaitForSingleObject', semaphore, 0), 258);
assert.equal(invoke('ReleaseSemaphore', semaphore, 2, data + 512), 1);
assert.equal(view.getUint32(data + 512, true), 0);
assert.equal(invoke('WaitForSingleObject', semaphore, 0), 0);
assert.equal(invoke('WaitForSingleObject', semaphore, 0), 0);
assert.equal(invoke('WaitForSingleObject', semaphore, 0), 258);

assert.equal(invoke('DuplicateHandle', 0xffffffff, manual, 0xffffffff, data + 512, 0, 0, 3), 1);
